/// Resolve a single modern Dubeolsik jamo to its QWERTY shortcut key.
/// Use only when matching commands. Composed syllables have no single key position.
pub fn dubeolsik_key(text: &str) -> Option<&'static str> {
    Some(match text {
        "ㅂ" | "ᄇ" | "ᆸ" => "q",
        "ㅈ" | "ᄌ" | "ᆽ" => "w",
        "ㄷ" | "ᄃ" | "ᆮ" => "e",
        "ㄱ" | "ᄀ" | "ᆨ" => "r",
        "ㅅ" | "ᄉ" | "ᆺ" => "t",
        "ㅛ" | "ᅭ" => "y",
        "ㅕ" | "ᅧ" => "u",
        "ㅑ" | "ᅣ" => "i",
        "ㅐ" | "ᅢ" => "o",
        "ㅔ" | "ᅦ" => "p",
        "ㅁ" | "ᄆ" | "ᆷ" => "a",
        "ㄴ" | "ᄂ" | "ᆫ" => "s",
        "ㅇ" | "ᄋ" | "ᆼ" => "d",
        "ㄹ" | "ᄅ" | "ᆯ" => "f",
        "ㅎ" | "ᄒ" | "ᇂ" => "g",
        "ㅗ" | "ᅩ" => "h",
        "ㅓ" | "ᅥ" => "j",
        "ㅏ" | "ᅡ" => "k",
        "ㅣ" | "ᅵ" => "l",
        "ㅋ" | "ᄏ" | "ᆿ" => "z",
        "ㅌ" | "ᄐ" | "ᇀ" => "x",
        "ㅊ" | "ᄎ" | "ᆾ" => "c",
        "ㅍ" | "ᄑ" | "ᇁ" => "v",
        "ㅠ" | "ᅲ" => "b",
        "ㅜ" | "ᅮ" => "n",
        "ㅡ" | "ᅳ" => "m",
        "ㅃ" | "ᄈ" => "Q",
        "ㅉ" | "ᄍ" => "W",
        "ㄸ" | "ᄄ" => "E",
        "ㄲ" | "ᄁ" | "ᆩ" => "R",
        "ㅆ" | "ᄊ" | "ᆻ" => "T",
        "ㅒ" | "ᅤ" => "O",
        "ㅖ" | "ᅨ" => "P",
        _ => return None,
    })
}
